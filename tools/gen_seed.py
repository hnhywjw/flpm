W = 10000  # 1万元 = 10000分

def y(v):
    """万元 -> 分"""
    return int(round(v * W))

L = []
def w(s=''):
    L.append(s)

def q(s):
    if s is None: return 'NULL'
    return "'" + str(s).replace("'", "''") + "'"

def ins(table, cols, rows):
    w('-- ' + table)
    w('INSERT INTO %s (%s) VALUES' % (table, ', '.join(cols)))
    vals = []
    for r in rows:
        vs = []
        for v in r:
            if v is None: vs.append('NULL')
            elif isinstance(v, (int, float)): vs.append(str(v))
            else: vs.append(q(v))
        vals.append('  (' + ', '.join(vs) + ')')
    w(',\n'.join(vals) + ';')
    w()

