-- 迁移 025：移除评标得分字段
-- ============================================================
-- 原因：评标得分拿不到。
--   招标方通常只公布中标结果和排名，不公布各家具体分数；
--   陪标公司更不会把分数告诉我们。
--   留着这个字段只会永远为空，还会让人误以为「该填没填」。
--
-- 保留 rank（排名）：排名是能拿到的（中标公告一般会公示候选人排序）。
-- ============================================================

